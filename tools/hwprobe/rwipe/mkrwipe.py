#!/usr/bin/env python3
"""mkrwipe.py - build the RWIPE kit's CF image: the C-Lab logo's wipe, timed in its real program.

    mkrwipe.py --base BASE.img --out KIT.img --game GAMEDIR [--rwipe RWIPE.COM] [--probe2 PROBE2.COM]

BASE.img is an earlier kit's raw CF image (the Xe10 IDE BIOS layout, 8 heads x 17 sectors, the DOS
partition at byte 69632, the user's own NEC MS-DOS 6.20). Every top-level folder of it except DOS
is removed. GAMEDIR is the root of the user's own game disk; only the files in GAME_FILES are
copied. The image holds NEC's DOS and game files, so it is NEVER committed.

THE KIT RUNS ITSELF in one boot (AUTOEXEC.BAT -> \\RWIPE\\RUN.BAT), about three minutes, and writes
everything to \\RWIPE\\RWIPE.TXT, WIPE1.TXT and WIPE2.TXT. Each step writes its flag file Snn.FLG
before it runs, so a step that hangs is skipped after a reset; DONE.FLG ends the sequence (DEL
\\RWIPE\\*.FLG starts it again).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OFF = 69632

GAME_FILES = ['BOOT.COM', 'ONGCHK.COM', 'PDR.COM', 'PPSDRV.COM', 'PMD.COM', 'PMDB2.COM',
              'CLABLOGO.EXE', 'OP.COM', 'RUSTY.FOT', 'MGXLOAD.BIN', 'DRUMS.PPS']

CONFIG = 'FILES=20\nBUFFERS=8\nSHELL=A:\\COMMAND.COM A:\\ /P\n'

AUTOEXEC = r'''@ECHO OFF
PATH A:\;A:\DOS
CD \RWIPE
IF EXIST DONE.FLG GOTO DONE
CALL RUN.BAT
GOTO END
:DONE
TYPE DONE.TXT
:END
'''

# The steps. Each: (flag, banner, commands). Rows tagged ND* run with no sound driver resident
# (RWIPE /S answers the logo program's driver check with 'absent'); BOOT runs the game's own
# shell, which loads its driver chain exactly as it does when the game starts, runs the logo and
# then OP.COM up to just after OP.COM's music stop (/P: the logo's voice is still playing when it
# starts, so the row holds the voice's start and its stop), and RWIPE ends it at the EXEC after
# that; DRV* rows then run the logo program with that chain resident, and OP* rows OP.COM alone.
# OP0 runs first, seconds after the boot as in the game, with no driver (/S answers its driver
# check 'absent', so it skips its PMD calls and exits where it would stop the music): on the core
# the empty floppy drives its CHDIR loop touches answer in about 11 ms soon after a boot and in
# 0.7-1.4 s each minutes later, so the row says which state the game itself meets.
STEPS = [
    ('S00', 'OP.COM alone right after boot, no drivers (the game reaches it as soon)',
     ['RWIPE /T:OP0 /S /P OP.COM']),
    ('S01', 'the wipe replica (PROBE2 /WIPE), no drivers', ['PROBE2 /WIPE > WIPE1.TXT']),
    ('S02', 'the real logo, no drivers (1 of 2)', ['RWIPE /T:ND1 /S CLABLOGO.EXE']),
    ('S03', 'the real logo, no drivers (2 of 2)', ['RWIPE /T:ND2 /S CLABLOGO.EXE']),
    ('S04', 'the real logo, no drivers, interrupts off in the wipe',
     ['RWIPE /T:NDC /S /C CLABLOGO.EXE']),
    ('S05', 'the game shell: its drivers, the real logo, then OP.COM to its music stop',
     ['RWIPE /T:BOOTP /B /P BOOT.COM']),
    ('S06', 'the real logo, drivers resident (1 of 2)', ['RWIPE /T:DRV1 CLABLOGO.EXE']),
    ('S07', 'the real logo, drivers resident (2 of 2)', ['RWIPE /T:DRV2 CLABLOGO.EXE']),
    ('S08', 'the real logo, drivers resident, no patch (overhead control)',
     ['RWIPE /T:DRVN /N CLABLOGO.EXE']),
    ('S09', 'the real logo, drivers resident, interrupts off in the wipe',
     ['RWIPE /T:DRVC /C CLABLOGO.EXE']),
    ('S10', 'the real logo, drivers resident, music not started',
     ['RWIPE /T:DRVS /S CLABLOGO.EXE']),
    ('S11', 'the wipe replica again, drivers resident', ['PROBE2 /WIPE > WIPE2.TXT']),
    ('S12', 'OP.COM alone to its music stop, drivers resident (1 of 2)', ['RWIPE /T:OP1 /P OP.COM']),
    ('S13', 'OP.COM alone to its music stop, drivers resident (2 of 2)', ['RWIPE /T:OP2 /P OP.COM']),
]
FIRST_DRV = 'S06'


def run_bat(only: set[str] | None = None) -> str:
    out = ['@ECHO OFF', 'REM RWIPE kit: generated by tools/hwprobe/rwipe/mkrwipe.py', '']
    for flag, banner, cmds in STEPS:
        if only and flag not in only and flag != FIRST_DRV:
            continue
        lab = 'X' + flag
        if flag == FIRST_DRV:
            out += ['REM the driver rows need the game shell\'s chain resident: after a reset',
                    'REM following S05 it is loaded here the way the shell loads it (DRV.BAT)',
                    'RWIPE /Q', 'IF NOT ERRORLEVEL 1 CALL DRV.BAT', '']
        if only and flag not in only:
            continue
        out += [f'IF EXIST {flag}.FLG GOTO {lab}',
                f'ECHO {flag}.FLG> {flag}.FLG',
                f'ECHO === RWIPE {flag}: {banner}']
        out += cmds
        out += [f':{lab}', '']
    out += ['ECHO DONE> DONE.FLG', 'TYPE DONE.TXT', '']
    return '\n'.join(out)


# The game shell's own chain (its EXEC list, BOOT.COM 0x319-0x379): ONGCHK, PDR /i, PPSDRV /40,
# then by ONGCHK's exit code PMD /k/m11/v0/e0/df8 (< 2), PMDB2 .../ds8/... (3) or .../ds16/... .
DRV_BAT = r'''@ECHO OFF
ECHO === RWIPE: loading the game's driver chain (DRV.BAT)
ONGCHK.COM
IF ERRORLEVEL 4 GOTO B16
IF ERRORLEVEL 3 GOTO B8
IF ERRORLEVEL 2 GOTO B16
PDR.COM /i
PPSDRV.COM /40
PMD.COM /k/m11/v0/e0/df8
GOTO END
:B8
PDR.COM /i
PPSDRV.COM /40
PMDB2.COM /k/m11/v0/e0/ds8/df24/dr8
GOTO END
:B16
PDR.COM /i
PPSDRV.COM /40
PMDB2.COM /k/m11/v0/e0/ds16/df24/dr8
:END
'''

DONE = r'''
 RWIPE kit: all steps are done.

 Switch the machine off, take the CF card out and bring it back (or copy
 the folder A:\RWIPE - RWIPE.TXT, WIPE1.TXT and WIPE2.TXT are the results).

 To run the kit again: DEL A:\RWIPE\*.FLG and A:\RWIPE\*.TXT except DONE.TXT,
 then reboot.
'''

README = r'''RWIPE kit (2026-11): times the C-Lab logo's wave ("wipe") inside the real
program, with and without the game's sound drivers, and the opening program's
start up to the moment it stops the logo's voice, on this machine.

It runs by itself at boot, about three minutes, no keys. The logo appears
several times (with music for some runs). When the screen says "all steps are
done", switch off and bring back the CF card.

Do not change the SETUP or the switches from how you normally run the game.
If the machine hangs on a step for more than 30 seconds, press RESET: the kit
skips that step and goes on.
'''


def crlf(t: str) -> bytes:
    return t.replace('\r\n', '\n').replace('\n', '\r\n').encode('ascii')


def sh(*a, **k):
    subprocess.run(a, check=True, **k)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--game', required=True)
    ap.add_argument('--rwipe', default=os.path.join(HERE, 'rwipe.com'))
    ap.add_argument('--probe2', default=os.path.join(os.path.dirname(HERE), 'probe2', 'probe2.com'))
    ap.add_argument('--work', default=None)
    ap.add_argument('--only', default=None, help='comma-separated steps (a test image; the driver '
                    'gate before S06 is always kept)')
    a = ap.parse_args()
    env = dict(os.environ, MTOOLS_SKIP_CHECK='1', MTOOLS_NO_VFAT='1')
    work = a.work or a.out + '.d'
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(os.path.join(work, 'RWIPE'))
    for fn in GAME_FILES:
        shutil.copy(os.path.join(a.game, fn), os.path.join(work, 'RWIPE', fn))
    shutil.copy(a.rwipe, os.path.join(work, 'RWIPE', 'RWIPE.COM'))
    shutil.copy(a.probe2, os.path.join(work, 'RWIPE', 'PROBE2.COM'))
    only = set(a.only.upper().split(',')) if a.only else None
    texts = {'RUN.BAT': run_bat(only), 'DRV.BAT': DRV_BAT, 'DONE.TXT': DONE, 'README.TXT': README}
    for n, t in texts.items():
        open(os.path.join(work, 'RWIPE', n), 'wb').write(crlf(t))
    open(os.path.join(work, 'CONFIG.SYS'), 'wb').write(crlf(CONFIG))
    open(os.path.join(work, 'AUTOEXEC.BAT'), 'wb').write(crlf(AUTOEXEC))
    shutil.copy(a.base, a.out)
    img = f'{a.out}@@{OFF}'
    ls = subprocess.run(['mdir', '-b', '-i', img, '::/'], env=env, check=True,
                        capture_output=True, text=True).stdout.split()
    for p in ls:
        name = p.rstrip('/').split('/')[-1].upper()
        if name in ('DOS', 'COMMAND.COM', 'IO.SYS', 'MSDOS.SYS'):
            continue
        if p.endswith('/'):
            sh('mdeltree', '-i', img, '::/' + name, env=env)
        elif name in ('CONFIG.SYS', 'AUTOEXEC.BAT', 'MENU.TXT'):
            sh('mdel', '-i', img, '::/' + name, env=env)
    sh('mcopy', '-o', '-i', img, os.path.join(work, 'CONFIG.SYS'), os.path.join(work, 'AUTOEXEC.BAT'),
       '::/', env=env)
    sh('mcopy', '-s', '-i', img, os.path.join(work, 'RWIPE'), '::/', env=env)
    sh('mdir', '-i', img, '::/RWIPE', env=env)
    h = hashlib.sha256(open(a.out, 'rb').read()).hexdigest()
    print(f'built {a.out} sha256 {h}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
